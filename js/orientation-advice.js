/* VolleyLive orientation advice: which orientation gives the most comfortable capture buttons on this device.
   Data: window.VolleyOrientationMatrix (js/orientation-matrix.js, generated by tools/orientation_matrix.py).
   Used by Settings > Recommended orientation (settings.js). Spec: docs/specs/UI-CAPTURE.md. */
(function (root) {
  // Below this difference (px) both orientations are considered equally comfortable.
  var TIE_PX = 4;

  // The device of the matrix whose screen matches (width, height) in CSS px, in either orientation.
  // exact is false when the closest device is only an approximation.
  function detect(width, height, matrix) {
    var devices = (matrix && matrix.devices) || [],
      short = Math.min(width, height),
      long = Math.max(width, height),
      best = null,
      bestGap = Infinity;
    devices.forEach(function (device) {
      var gap = Math.abs(device.width - short) + Math.abs(device.height - long);
      if (gap < bestGap) {
        best = device;
        bestGap = gap;
      }
    });
    return best ? { device: best, exact: bestGap <= 4 } : null;
  }

  // 'portrait', 'landscape' or 'either' for one mode entry {portrait: {button, fits}, landscape: {...}}.
  function advise(entry) {
    var p = entry.portrait,
      l = entry.landscape;
    if (p.fits !== l.fits) return p.fits ? 'portrait' : 'landscape';
    if (Math.abs(p.button - l.button) < TIE_PX) return 'either';
    return p.button > l.button ? 'portrait' : 'landscape';
  }

  root.VolleyOrientation = { detect: detect, advise: advise, TIE_PX: TIE_PX };
})(typeof window !== 'undefined' ? window : globalThis);

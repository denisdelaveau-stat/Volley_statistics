"""Measure every capture mode on iPhone / iPad screens, portrait and landscape, and write js/orientation-matrix.js.

Usage: python tools/orientation_matrix.py

For each device the capture screen is rendered at the size an installed PWA really gets (CSS screen size minus the
iOS safe areas). The measured value is the smallest side of the input buttons (players, actions, statuses), so a
larger value means bigger touch targets. "fits" is false when any of these buttons lies outside the screen.
Settings > "Orientation conseillée" reads the result (settings.js) to recommend an orientation per mode.
Run it again after a layout change of the capture modes.
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests" / "support"))
from playwright.sync_api import sync_playwright  # noqa: E402
from capture_support import open_runtime  # noqa: E402

# name, CSS width and height in portrait, safe areas in portrait (top, bottom) and landscape (each side, bottom)
DEVICES = [
    ("iPhone 13 / 14", 390, 844, (47, 34), (47, 21)),
    ("iPhone 15 / 16", 393, 852, (59, 34), (59, 21)),
    ("iPhone 15 / 16 Pro Max", 430, 932, (59, 34), (59, 21)),
    ("iPhone 17", 402, 874, (62, 34), (62, 21)),
    ("iPhone 17 Pro Max", 440, 956, (62, 34), (62, 21)),
    ("iPad mini", 744, 1133, (24, 20), (0, 20)),
    ("iPad Air 11", 820, 1180, (24, 20), (0, 20)),
    ("iPad Pro 13", 1032, 1376, (24, 20), (0, 20)),
]
MODES = ["FOCUS", "SPEED", "FLOW", "GAMEPAD"]
CORE = (
    "[data-runtime-author],[data-runtime-action],[data-runtime-result],"
    "[data-gamepad-player],[data-gamepad-action],[data-gamepad-status]"
)
MEASURE = """(selector) => {
  let min = Infinity, fits = true;
  for (const e of document.querySelectorAll(selector)) {
    if (e === document.documentElement) continue;
    const r = e.getBoundingClientRect();
    if (!r.width || !r.height || getComputedStyle(e).visibility === 'hidden') continue;
    min = Math.min(min, r.width, r.height);
    if (r.left < -1 || r.right > innerWidth + 1 || r.top < -1 || r.bottom > innerHeight + 1) fits = false;
  }
  return {min: Math.round(min), fits};
}"""


def measure(browser, mode, viewport):
    class Pages:
        def new_page(self, viewport):
            return browser.new_page(viewport=viewport, has_touch=True)

    page, errors = open_runtime(Pages(), mode, viewport)
    page.wait_for_timeout(200)
    steps = [page.evaluate(MEASURE, CORE)]
    if mode == "FOCUS":
        page.locator("[data-runtime-author]").first.click()
        page.wait_for_timeout(100)
        steps.append(page.evaluate(MEASURE, CORE))
        page.locator("[data-runtime-action]:not([disabled])").first.click()
        page.wait_for_timeout(100)
        steps.append(page.evaluate(MEASURE, CORE))
    page.close()
    if errors:
        raise SystemExit(f"{mode} {viewport}: {errors}")
    return {"button": min(s["min"] for s in steps), "fits": all(s["fits"] for s in steps)}


def main():
    devices = []
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=True)
        for name, width, height, (top, bottom), (side, land_bottom) in DEVICES:
            sizes = {
                "portrait": {"width": width, "height": height - top - bottom},
                "landscape": {"width": height - 2 * side, "height": width - land_bottom},
            }
            modes = {
                mode: {orientation: measure(browser, mode, size) for orientation, size in sizes.items()}
                for mode in MODES
            }
            devices.append({"name": name, "width": width, "height": height, "modes": modes})
            print(name, {m: (v["portrait"]["button"], v["landscape"]["button"]) for m, v in modes.items()})
        browser.close()
    data = {"generated": date.today().isoformat(), "devices": devices}
    (ROOT / "js" / "orientation-matrix.js").write_text(
        "/* Generated by tools/orientation_matrix.py: smallest input-button side (px) per device, mode and\n"
        "   orientation, and whether every input button fits on screen. Read by settings.js. */\n"
        "window.VolleyOrientationMatrix = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main()
